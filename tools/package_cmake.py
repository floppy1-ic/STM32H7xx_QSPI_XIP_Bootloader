def copy_tree(src: Path, dst: Path) -> int:
    """Recursively copy src into dst, returning number of files copied."""
    files = 0
    for root, _dirs, fnames in os.walk(src):
        rel = Path(root).relative_to(src)
        out_dir = dst / rel
        out_dir.mkdir(parents=True, exist_ok=True)
        for f in fnames:
            shutil.copy2(Path(root) / f, out_dir / f)
            files += 1
    return files


