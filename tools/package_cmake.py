def existing_dirs(paths: list[Path]) -> list[Path]:
    seen: set[Path] = set()
    dirs: list[Path] = []
    for p in paths:
        if not p or str(p) == "." or not p.exists():
            continue
        resolved = p.resolve()
        if resolved not in seen:
            seen.add(resolved)
            dirs.append(resolved)
    return dirs


def cubeide_search_roots(root: Path) -> list[Path]:
    env = os.environ
    home = Path(env.get("HOME") or env.get("USERPROFILE") or "")
    candidates: list[Path] = [
        root,
        root.parent,
        # Explicit environment overrides honoured on every OS.
        Path(env.get("STM32CUBEIDE_TOOLCHAIN", "")),
        Path(env.get("STM32CUBEIDE_PATH", "")),
        Path(env.get("STM32CubeIDE", "")),
    ]

    if os.name == "nt":
        candidates += [
            Path(env.get("ProgramFiles", "")) / "STMicroelectronics",
            Path(env.get("ProgramFiles(x86)", "")) / "STMicroelectronics",
            Path(env.get("LOCALAPPDATA", "")) / "Programs" / "STMicroelectronics",
            home / "STMicroelectronics",
            Path("C:/ST"),
            Path("C:/STMicroelectronics"),
        ]
    elif sys.platform == "darwin":
        candidates += [
            Path("/Applications"),
            Path("/Applications/STMicroelectronics"),
            Path("/Library/STMicroelectronics"),
            home / "Applications",
            home / "Applications/STMicroelectronics",
            home / "STMicroelectronics",
            Path("/opt/st"),
            Path("/opt/STMicroelectronics"),
        ]
    else:
        candidates += [
            Path("/opt/st"),
            Path("/opt/STMicroelectronics"),
            Path("/usr/local/STMicroelectronics"),
            home / "STMicroelectronics",
            home / ".local/share/STMicroelectronics",
            home / "Applications/STMicroelectronics",
        ]

    return existing_dirs(candidates)


def discover_arm_gcc(root: Path, explicit_bin: str | None) -> Path | None:
    if explicit_bin:
        toolchain_path = Path(explicit_bin).expanduser().resolve()
        gcc = toolchain_path if toolchain_path.is_file() else toolchain_path / exe("arm-none-eabi-gcc")
        return gcc if gcc.exists() else None

    found = shutil.which("arm-none-eabi-gcc")
    if found:
        return Path(found).resolve()

    gcc_name = exe("arm-none-eabi-gcc")
    patterns = [
        # Windows / generic capitalised CubeIDE folders.
        f"STM32CubeIDE*/plugins/**/tools/bin/{gcc_name}",
        f"STM32CubeIDE*/plugins/**/bin/{gcc_name}",
        f"STM32CubeIDE*/STM32CubeIDE/plugins/**/tools/bin/{gcc_name}",
        f"STM32CubeIDE*/STM32CubeIDE/plugins/**/bin/{gcc_name}",
        # Linux installer folders typically lowercase + versioned.
        f"stm32cubeide*/plugins/**/tools/bin/{gcc_name}",
        f"stm32cubeide*/plugins/**/bin/{gcc_name}",
        # macOS .app bundle layout.
        f"STM32CubeIDE*.app/Contents/Eclipse/plugins/**/tools/bin/{gcc_name}",
        f"STM32CubeIDE*.app/Contents/Eclipse/plugins/**/bin/{gcc_name}",
        # When the search root is already inside an Eclipse install.
        f"plugins/**/tools/bin/{gcc_name}",
        f"plugins/**/bin/{gcc_name}",
        # Catch-all fallback (slow but correct).
        f"**/{gcc_name}",
    ]
    matches: list[Path] = []
    for base in cubeide_search_roots(root):
        for pattern in patterns:
            matches.extend(
                p for p in base.glob(pattern)
                if p.is_file() and p.name.lower() == gcc_name.lower()
            )
    if not matches:
        return None

    # Prefer the newest CubeIDE bundled toolchain when multiple versions exist.
    matches.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return matches[0].resolve()


