def validate_project_name(name: str) -> None:
    if not re.match(r"^[A-Za-z][A-Za-z0-9_.-]*$", name):
        err(f"Invalid project name: {name!r}. "
            f"Must start with a letter and contain only letters, digits, '_', '.', '-'.")
        sys.exit(2)


def verify_source_layout(src: Path) -> None:
    missing: list[str] = []
    for rel, label in REQUIRED.items():
        if (src / rel).exists():
            ok(f"{label:<18}  {rel}")
        else:
            err(f"{label:<18}  {rel}  (NOT FOUND)")
            missing.append(rel)
    if missing:
        err("Aborting: the source project is missing required files (see above).")
        sys.exit(3)


def prepare_destination(dst: Path, force: bool) -> None:
    if dst.exists():
        if not force:
            err(f"Destination already exists: {dst}\n  use --force to overwrite.")
            sys.exit(4)
        warn(f"Removing existing destination: {dst}")
        shutil.rmtree(dst)
    for sub in ("", "main_h", "main_c", "startup",
                "hal_driver", "peripherals", "linker", "output", "cmake"):
        (dst / sub).mkdir(parents=True, exist_ok=True)
    ok(f"Created scaffolding at {dst}")


def copy_sources(src: Path, dst: Path) -> dict[str, int]:
    stats: dict[str, int] = {}

    # os_sys.c (renamed from main.c)
    shutil.copy2(src / "Core/Src/main.c", dst / "os_sys.c")
    stats["os_sys.c"] = 1
    ok("Core/Src/main.c  ->  os_sys.c")

    # main_h: Core/Inc/*
    stats["main_h"] = copy_tree(src / "Core/Inc", dst / "main_h")
    ok(f"Core/Inc/*  ->  main_h/  ({stats['main_h']} files)")

    # main_c: Core/Src/* except main.c
    n = 0
    for p in (src / "Core/Src").iterdir():
        if p.is_file() and p.name != "main.c":
            shutil.copy2(p, dst / "main_c" / p.name)
            n += 1
    stats["main_c"] = n
    ok(f"Core/Src/*  (excluding main.c)  ->  main_c/  ({n} files)")

    # startup
    stats["startup"] = copy_tree(src / "Core/Startup", dst / "startup")
    ok(f"Core/Startup/*  ->  startup/  ({stats['startup']} files)")

    # hal_driver: Drivers/CMSIS + Drivers/STM32H7xx_HAL_Driver
    for d in ("CMSIS", "STM32H7xx_HAL_Driver"):
        n = copy_tree(src / f"Drivers/{d}", dst / "hal_driver" / d)
        stats[f"hal_driver/{d}"] = n
        ok(f"Drivers/{d}  ->  hal_driver/{d}/  ({n} files)")

    # peripherals: copy the complete Peripherals tree so future drivers are included.
    stats["peripherals"] = copy_tree(src / "Peripherals", dst / "peripherals")
    ok(f"Peripherals/*  ->  peripherals/  ({stats['peripherals']} files)")

    # linker scripts
    n = 0
    for ld in ("STM32H750VBTX_FLASH.ld", "STM32H750VBTX_RAM.ld"):
        shutil.copy2(src / ld, dst / "linker" / ld)
        n += 1
    stats["linker"] = n
    ok(f"*.ld  ->  linker/  ({n} files)")

    return stats


